#!/usr/bin/env python3
"""Render the dex2jar-skills feature tree as a Unicode tree.

Single source of truth for the "feature tree" shown in README.md and
README.zh-CN.md. Unlike the Mermaid mindmap (which only renders on GitHub),
this produces a plain-text box-drawing tree that displays in *any* Markdown
viewer, terminal, or plain text — and stays in sync because both READMEs are
generated from the TREE below.

Usage:
    python3 tools/feature_tree.py                 # print English tree
    python3 tools/feature_tree.py --lang zh       # print Chinese tree
    python3 tools/feature_tree.py --write         # inject both into the READMEs
    python3 tools/feature_tree.py --check         # verify READMEs are in sync (CI)

The injected region is delimited in each README by:
    <!-- FEATURE-TREE:START (auto-generated by tools/feature_tree.py) -->
    <!-- FEATURE-TREE:END -->
"""
