import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Each node is (en_label, zh_label, [children]). Leaves have an empty child list.
# This mirrors the Mermaid mindmap so the two stay conceptually identical.
