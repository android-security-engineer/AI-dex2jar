# Box-drawing connectors.
TEE, ELBOW, PIPE, BLANK = "├── ", "└── ", "│   ", "    "

START = "<!-- FEATURE-TREE:START (auto-generated by tools/feature_tree.py) -->"
END = "<!-- FEATURE-TREE:END -->"


def _label(node, lang: str) -> str:
    en, zh, _children = node
    return zh if lang == "zh" else en


def _children(node):
    return node[2]


def render(node, lang: str = "en") -> str:
    """Return the tree rooted at ``node`` as a Unicode box-drawing string."""
    lines = [_label(node, lang)]

    def walk(children, prefix: str) -> None:
        last = len(children) - 1
        for i, child in enumerate(children):
            connector = ELBOW if i == last else TEE
            lines.append(prefix + connector + _label(child, lang))
            kids = _children(child)
            if kids:
                walk(kids, prefix + (BLANK if i == last else PIPE))

    walk(_children(node), "")
    return "\n".join(lines)


def _block(lang: str) -> str:
    """The full Markdown region (markers + fenced tree) for one language."""
    tree = render(TREE, lang)
    return f"{START}\n```text\n{tree}\n```\n{END}"


def _readmes():
    return {
        "en": os.path.join(ROOT, "README.md"),
        "zh": os.path.join(ROOT, "README.zh-CN.md"),
    }


def _inject(text: str, block: str) -> str:
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit(
            "FEATURE-TREE markers not found — add the START/END comment pair first"
        )
    return pattern.sub(lambda _m: block, text)


def cmd_write() -> int:
    for lang, path in _readmes().items():
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
        new = _inject(text, _block(lang))
        if new != text:
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(new)
            print(f"  updated {os.path.relpath(path, ROOT)}")
        else:
            print(f"  unchanged {os.path.relpath(path, ROOT)}")
    return 0


def cmd_check() -> int:
    rc = 0
    for lang, path in _readmes().items():
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
        if _block(lang) not in text:
            print(f"  ❌ {os.path.relpath(path, ROOT)} feature tree is stale "
                  f"— run: python3 tools/feature_tree.py --write")
            rc = 1
        else:
            print(f"  ✅ {os.path.relpath(path, ROOT)} feature tree in sync")
    return rc


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Render the README feature tree.")
    ap.add_argument("--lang", choices=("en", "zh"), default="en",
                    help="language for plain stdout render (default: en)")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true",
                   help="inject the tree into README.md and README.zh-CN.md")
    g.add_argument("--check", action="store_true",
                   help="verify both READMEs are in sync (exit 1 if stale)")
    args = ap.parse_args(argv)

    if args.write:
        return cmd_write()
    if args.check:
        return cmd_check()
    print(render(TREE, args.lang))
    return 0


if __name__ == "__main__":
    sys.exit(main())
